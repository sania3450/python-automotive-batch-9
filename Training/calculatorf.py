print("Calculator Function\n")
def add(num1, num2):
    return num1 + num2

def sub(num1, num2):
    return num1 - num2

def mul(num1, num2):
    return num1 * num2

def div(num1, num2):
    return num1 / num2



print("Addition:", add(12, 1))        
print("Subtraction:", sub(15, 7))     
print("Multiplication:", mul(18, 8)) 
print("Division:", div(45, 9))        